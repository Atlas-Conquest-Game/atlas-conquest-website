"""Per-language font stylesheets for the localized pages: site/css/i18n/<file>.css.

The title font, OptimusPrinceps, is Latin only and lacks Polish's ą ć ę ł ń ś ź ż. Those
letters and Cyrillic come from a small subset of Cormorant SC (the game's own Russian
title font, SIL OFL), served from site/assets/media/fonts/i18n/. The browser takes each
missing glyph from the next font in the stack, so Latin text keeps OptimusPrinceps.

Japanese, Korean and Chinese use the reader's own system fonts: every desktop and phone
ships good CJK faces, and a webfont covering a page's characters would cost hundreds of
KB. Their stylesheets only extend the stacks and drop the wide letter-spacing the Latin
headings use.

Needs fontTools and brotli (scripts/requirements-dev.txt). Run after changing a font:
    python scripts/build_i18n_fonts.py
"""
from __future__ import annotations

from pathlib import Path

from fontTools import subset

REPO_ROOT = Path(__file__).resolve().parent.parent
SITE = REPO_ROOT / "site"
CSS_DIR = SITE / "css" / "i18n"
FONT_DIR = SITE / "assets" / "media" / "fonts" / "i18n"
CORMORANT = REPO_ROOT.parent.parent / "atlas-conquest" / "atlas-conquest" / "Assets" / "Fonts" / "Localization" / "CormorantSC" / "CormorantSC-Bold.ttf"

POLISH = "ąćęłńśźżĄĆĘŁŃŚŹŻ"
CYRILLIC = "U+0400-045F, U+0490-0491, U+2116"

DISPLAY_VARS = ("--display", "--font-display", "--ac-font-display")
BODY_VARS = {"--sans": "'Alegreya Sans', 'Segoe UI', system-ui, -apple-system",
             "--sc": "'Alegreya Sans SC', 'Alegreya Sans', system-ui",
             "--font-body": "'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI'",
             "--ac-font-body": "'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI'"}
LATIN_DISPLAY = "'OptimusPrinceps', 'Cinzel', 'Trajan Pro'"

CJK = {
    "ja.css": ("'Yu Mincho', 'YuMincho', 'Hiragino Mincho ProN', 'Noto Serif JP', 'Noto Serif CJK JP'",
               "'Yu Gothic UI', 'Yu Gothic', 'Hiragino Sans', 'Noto Sans JP', 'Noto Sans CJK JP', Meiryo", "ja"),
    "ko.css": ("'Batang', 'AppleMyungjo', 'Noto Serif KR', 'Noto Serif CJK KR'",
               "'Malgun Gothic', 'Apple SD Gothic Neo', 'Noto Sans KR', 'Noto Sans CJK KR'", "ko"),
    "zh-cn.css": ("'SimSun', 'Songti SC', 'Noto Serif SC', 'Noto Serif CJK SC'",
                  "'Microsoft YaHei', 'PingFang SC', 'Noto Sans SC', 'Noto Sans CJK SC'", "zh-CN"),
}

HEADER = "/* Generated by scripts/build_i18n_fonts.py; linked from the {lang} pages by scripts/build_i18n.py. */\n"


def subset_font(out: Path, unicodes: list[int]) -> int:
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    font = subset.load_font(str(CORMORANT), opts)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    out.parent.mkdir(parents=True, exist_ok=True)
    subset.save_font(font, str(out), opts)
    return out.stat().st_size


def stack_vars(display: str, extra_body: str = "") -> str:
    lines = [f"  {v}: {display};" for v in DISPLAY_VARS]
    if extra_body:
        lines += [f"  {v}: {base}, {extra_body}, sans-serif;" for v, base in BODY_VARS.items()]
    return ":root {\n" + "\n".join(lines) + "\n}\n"


def face(family: str, file: str, unicode_range: str) -> str:
    return (f"@font-face {{\n  font-family: '{family}';\n  src: url('../../assets/media/fonts/i18n/{file}') format('woff2');\n"
            f"  font-weight: 100 900;\n  font-display: swap;\n  unicode-range: {unicode_range};\n}}\n")


def main() -> None:
    CSS_DIR.mkdir(parents=True, exist_ok=True)
    cyr = sorted(set(range(0x400, 0x460)) | {0x490, 0x491, 0x2116})
    n = subset_font(FONT_DIR / "cormorant-sc-cyrillic.woff2", cyr)
    (CSS_DIR / "ru.css").write_text(HEADER.format(lang="Russian") + face("AC Display Cyrillic", "cormorant-sc-cyrillic.woff2", CYRILLIC)
                                    + stack_vars(f"{LATIN_DISPLAY}, 'AC Display Cyrillic', Georgia, serif"), encoding="utf-8", newline="\n")
    print(f"  ru: Cormorant SC Cyrillic, {n // 1024} KB")
    pl = [ord(c) for c in POLISH]
    n = subset_font(FONT_DIR / "cormorant-sc-polish.woff2", pl)
    rng = ", ".join(f"U+{c:04X}" for c in sorted(set(pl)))
    (CSS_DIR / "pl.css").write_text(HEADER.format(lang="Polish") + face("AC Display Polish", "cormorant-sc-polish.woff2", rng)
                                    + stack_vars(f"'OptimusPrinceps', 'AC Display Polish', 'Cinzel', 'Trajan Pro', Georgia, serif"),
                                    encoding="utf-8", newline="\n")
    print(f"  pl: Cormorant SC Polish letters, {n // 1024} KB")
    for file, (serif, sans, lang) in CJK.items():
        css = HEADER.format(lang=lang) + stack_vars(f"{LATIN_DISPLAY}, {serif}, serif", sans)
        # The Latin headings' wide tracking and case transforms make CJK hard to read.
        css += ("body, body * {\n  letter-spacing: normal !important;\n}\n"
                "h1, h2, h3, h4, p, a, button, span, li, dt, dd, summary {\n  word-break: normal;\n  line-break: strict;\n}\n")
        (CSS_DIR / file).write_text(css, encoding="utf-8", newline="\n")
        print(f"  {lang}: system CJK fonts")


if __name__ == "__main__":
    main()
